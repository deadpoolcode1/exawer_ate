"""TestScript IR → JSystem/Java source for Exaware's `cmp-tests-project`.

Emits the four artifacts a real suite in that repo consists of (see
`.claude/skills/exaware-framework`):

  1. `TCnn_*.java`      — `extends CmpTestCase`, one `@Test`, steps rendered as
                          `CompassReporter.stopAndStartLevel(++level + ". …")`
  2. `EvpnParams.java`  — `implements ISuiteParams`; every expected value
  3. `EvpnUtils.java`   — the verify helpers the tests call
  4. `EvpnCommands.java`— `implements ICmpCliCmd`; the CLI templates

Conventions are copied from `cmp/tests/vpls`, which is the closest existing
analog (`TC05_VplsMacAgingTime` is a MAC-aging test driven by suspending and
unsuspending IXIA traffic items — structurally the same shape as the M2 flows).

Target is Java 8 (`maven-compiler-plugin` source/target 1.8), so: no `var`,
no `List.of`, no diamond-less generics shortcuts.

**Steps carrying `todo` emit `CompassReporter.warning(...)`, never a passing
assertion.** An expected-value table that nobody has validated against real
device output must not be able to report a green run.
"""
