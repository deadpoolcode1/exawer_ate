def _arg_expr(arg: str, lab: LabProfile) -> str:
    """One step argument as Java.

    Interface names are the exception to "arguments are literals". The lab
    profile spells an attachment circuit `agg-eth-1.100`, but that is a
    PLACEHOLDER: which port the circuit lives on is a property of the testbed,
    and pc-3080's are `x-eth 0/0/8`. Sending the placeholder text to the device
    is how three configuration commands came back
    `syntax error: "-1.100" is not a valid value`. Resolve it from the SUT
    instead, exactly as the `.cfg` does through `bringUpParams.crt`.
    """
    for i, ac in enumerate(lab.acs):
        if arg == ac.ac_interface:
            return f"evpnUtils.acInterface({i})"
    return _jstr(arg)


def _render_step(step: Step, lab: LabProfile,
                 captured: set[str] | None = None) -> list[str]:
    """One IR step → its Java lines (level banner + the call)."""
    out: list[str] = []
    if step.req_ids:
        out.append(_ascii(
            f"        // {step.id} - covers {', '.join(step.req_ids)}"))
    else:
        out.append(f"        // {step.id}")
    out.append("        CompassReporter.stopAndStartLevel(++level + "
               f"{_jstr('. ' + step.text)});")

    args = ", ".join(_arg_expr(a, lab) for a in step.args)
    cmd_expr = f"EvpnCommands.{step.command}" + (f".args({args})" if args else "")

    if step.kind is StepKind.CONFIG:
        out.append(f"        evpnUtils.configAndVerifyAccepted({cmd_expr});")
    elif step.kind in (StepKind.VERIFY_CLI, StepKind.VERIFY_ROUTE):
        expect = (f"testParams.{step.expect_key}" if step.expect_key
                  else "new String[] {}")
        out.append(f"        evpnUtils.verifyShowLines({cmd_expr}, {expect});")
    elif step.kind is StepKind.TRAFFIC_CREATE:
        out.append("        evpnUtils.createTrafficItems();")
    elif step.kind is StepKind.TRAFFIC_STATE:
        for ti in step.traffic_items:
            flag = "true" if step.enabled else "false"
            out.append(f"        evpnUtils.setTrafficItemState("
                       f"testParams.{ti}, {flag});")
    elif step.kind is StepKind.TRAFFIC_START:
        out.append("        evpnUtils.setTrafficItemState("
                   "testParams.TI_AC1_TO_AC2, true);")
        out.append("        evpnUtils.startTraffic();")
    elif step.kind is StepKind.TRAFFIC_STOP:
        for ti in step.traffic_items:
            out.append(f"        evpnUtils.setTrafficItemState("
                       f"testParams.{ti}, false);")
        out.append("        evpnUtils.stopTraffic();")
    elif step.kind is StepKind.WAIT:
        out.append(f"        evpnUtils.waitSeconds("
                   f"testParams.MAC_AGING_TIME_IN_SEC, {_jstr(step.text)});")
    elif step.kind is StepKind.VERIFY_IXIA:
        expect = (f"testParams.{step.expect_key}" if step.expect_key
                  else "new String[] {}")
        out.append(f"        evpnUtils.verifyIxiaStatistics("
                   f"{_jstr(step.text)}, {expect});")
    elif step.kind is StepKind.VERIFY_NO_EVENT:
        # Snapshot steps are emitted by `emit_test` (they need to assign into a
        # method-scoped local); anything else compares against that snapshot.
        out.append("        evpnUtils.verifyOutputUnchanged(routesBefore, "
                   f"{cmd_expr}, {_jstr(step.text)});")

    # A step whose expectation has since been captured from a device is no
    # longer "awaiting real device output", so it must not keep saying so. The
    # warning exists to stop an unvalidated table looking green; once the table
    # is real, the assertion speaks for itself.
    if step.todo and not (captured and step.expect_key in captured):
        out.append(f"        CompassReporter.warning({_jstr(step.id + ': ' + step.todo)});")
    out.append("")
    return out


def emit_test(script: TestScript, lab: LabProfile,
               captured: set[str] | None = None) -> JavaFile:
    extra = [script.summary]
    if script.depends_on:
        extra.append(
            "Prerequisite: " + ", ".join(script.depends_on)
            + ". Those flows must have run (or their configuration be present "
              "in the bring-up) before this test.")
    if script.covered_req_ids:
        extra.append("Covers: " + ", ".join(script.covered_req_ids) + ".")
    todos = script.open_todos
    if todos:
        extra.append(
            f"{len(todos)} of {len(script.steps)} steps still need real device "
            "output before their assertions are meaningful; those steps report "
            "a warning rather than a pass.")

    needs_snapshot = any(
        s.kind is StepKind.VERIFY_NO_EVENT and s.text.lower().startswith("snapshot")
        for s in script.steps)

    lines = [
        f"package {PACKAGE};",
        "",
        "import org.junit.Test;",
        "",
        "import cmp.infra.CmpRouter;",
        "import cmp.infra.CmpTestCase;",
        "import cmp.infra.bringUp.DevicesSut;",
        "import cmp.infra.ixia.Ixia;",
        "import cmp.infra.reporter.CompassReporter;",
        "",
        _header(f"{script.flow_id} - {script.title}", extra),
        f"public class {script.class_name} extends CmpTestCase {{",
        "",
        "    @Test",
        f"    public void {script.method_name}() throws Exception {{",
        "",
        f"        CmpRouter cmp1 = getDevices().getCmpRouter(DevicesSut.{lab.dut});",
        f"        Ixia ixia = getDevices().getIxiaRouter(DevicesSut.{lab.ixia});",
        "        EvpnParams testParams = (EvpnParams) getSuiteParams();",
        "        EvpnUtils evpnUtils = new EvpnUtils(testParams, cmp1, ixia);",
        "",
        "        int level = 0;",
    ]
    if needs_snapshot:
        lines.append("        String routesBefore = null;")
    lines.append("")

    for step in script.steps:
        if (step.kind is StepKind.VERIFY_NO_EVENT
                and step.text.lower().startswith("snapshot")):
            args = ", ".join(_jstr(a) for a in step.args)
            cmd_expr = (f"EvpnCommands.{step.command}"
                        + (f".args({args})" if args else ""))
            lines.append(_ascii(
                f"        // {step.id} - covers {', '.join(step.req_ids)}"))
            lines.append("        CompassReporter.stopAndStartLevel("
                         f"++level + {_jstr('. ' + step.text)});")
            lines.append(f"        routesBefore = evpnUtils.snapshot({cmd_expr});")
            lines.append("")
            continue
        lines += _render_step(step, lab, captured)

    lines += [
        "        // PIPELINE RULE: a test that verified nothing is not a pass.",
        "        evpnUtils.assertSomethingWasVerified();",
        "        CompassReporter.stopLevel();",
        "    }",
        "}",
        "",
    ]
    return JavaFile(path=f"cmp/tests/evpn/{script.class_name}.java",
                    content="\n".join(lines))


def emit_all(scripts: list[TestScript], lab: LabProfile,
             captures: dict | None = None) -> list[JavaFile]:
    """Every artifact of the suite.

    `captures` maps an expect_key to one usable `ate capture` result. Keys it
    covers become real assertions carrying their provenance; keys it does not
    stay empty and keep warning.
    """
    captured = set(captures or {})
    files = [emit_commands(), emit_params(scripts, lab, captures),
             emit_utils(lab)]
    files += [emit_test(s, lab, captured) for s in scripts]
    return files
