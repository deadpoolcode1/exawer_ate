from dataclasses import dataclass

from ate.codegen.commands import all_commands
from ate.codegen.lab import LabProfile
from ate.codegen.script_ir import Step, StepKind, TestScript

PACKAGE = "cmp.tests.evpn"
GENERATED_BY = (
    "Generated by the ATE test-plan pipeline from the EVPN SFS, the EVPN CLI "
    "doc and RFC 7432bis."
)


@dataclass
class JavaFile:
    """One emitted source file, addressed by its package-relative path."""

    path: str          # "cmp/tests/evpn/EvpnUtils.java"
    content: str

    @property
    def class_name(self) -> str:
        return self.path.rsplit("/", 1)[-1][: -len(".java")]


#: The plan's prose uses typographic characters that have no place in Java
#: source — Exaware's tree is plain ASCII throughout. Fold rather than escape,
#: so the run report stays readable.
_ASCII_FOLD = {
    "→": "->", "←": "<-", "↔": "<->",
    "—": "-", "–": "-", "‑": "-",
    "§": "section ", "≥": ">=", "≤": "<=",
    "‘": "'", "’": "'", "“": '"', "”": '"',
    "…": "...", " ": " ", "·": "-",
}


def _ascii(s: str) -> str:
    for bad, good in _ASCII_FOLD.items():
        s = s.replace(bad, good)
    return s.encode("ascii", "replace").decode("ascii")


def _jstr(s: str) -> str:
    """Render a Python string as an ASCII-safe Java string literal."""
    out = _ascii(s).replace("\\", "\\\\").replace('"', '\\"')
    return '"' + out.replace("\n", "\\n") + '"'


def _wrap_javadoc(text: str, indent: str = " ") -> list[str]:
    """Wrap prose into javadoc continuation lines at ~76 columns."""
    words = _ascii(text).split()
    lines: list[str] = []
    cur = ""
    for w in words:
        if len(cur) + len(w) + 1 > 74:
            lines.append(cur)
            cur = w
        else:
            cur = f"{cur} {w}".strip()
    if cur:
        lines.append(cur)
    return [f"{indent}* {ln}" for ln in lines]


def _header(summary: str, extra: list[str] | None = None) -> str:
    body = ["/**"] + _wrap_javadoc(summary)
    if extra:
        body.append(" *")
        for e in extra:
            body += _wrap_javadoc(e)
    body.append(" *")
    body += _wrap_javadoc(GENERATED_BY)
    body.append(" */")
    return "\n".join(body)


