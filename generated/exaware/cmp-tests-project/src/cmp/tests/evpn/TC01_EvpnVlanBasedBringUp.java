package cmp.tests.evpn;

import org.junit.Test;

import cmp.infra.CmpRouter;
import cmp.infra.CmpTestCase;
import cmp.infra.bringUp.DevicesSut;
import cmp.infra.ixia.Ixia;
import cmp.infra.reporter.CompassReporter;

/**
 * FLOW-010 - EVPN VLAN-based bring-up with three local ACs
 *
 * Configure a vlan-based EVI on the DUT, bind all three IXIA-backed access
 * circuits, and confirm the service comes up and advertises its Type-3 IMET
 * route. Prerequisite for TC02 and TC03.
 * Covers: EVPNS-REQ#30, EVPNS-REQ#40, EVPNS-REQ#50, EVPNS-REQ#380,
 * RFC7432bis-section 7.3, RFC7432bis-section 11.
 * 3 of 10 steps still need real device output before their assertions are
 * meaningful; those steps report a warning rather than a pass.
 *
 * Generated by the ATE test-plan pipeline from the EVPN SFS, the EVPN CLI
 * doc and RFC 7432bis.
 */
public class TC01_EvpnVlanBasedBringUp extends CmpTestCase {

    @Test
    public void evpnVlanBasedBringUp() throws Exception {

        CmpRouter cmp1 = getDevices().getCmpRouter(DevicesSut.CMP1);
        Ixia ixia = getDevices().getIxiaRouter(DevicesSut.IXIA1);
        EvpnParams testParams = (EvpnParams) getSuiteParams();
        EvpnUtils evpnUtils = new EvpnUtils(testParams, cmp1, ixia);

        int level = 0;

        // FLOW-010.S01 - covers EVPNS-REQ#30, EVPNS-REQ#40, EVPNS-REQ#50, EVPNS-REQ#380
        CompassReporter.stopAndStartLevel(++level + ". Create EVPN instance evi-1 with service-type vlan-based");
        cmp1.configAndValidate(EvpnCommands.CONFIGURE_L2_SERVICES_EVPN_$_SERVICE_TYPE_$.args("evi-1", "vlan-based"));

        // FLOW-010.S02 - covers EVPNS-REQ#30, EVPNS-REQ#40, EVPNS-REQ#50, EVPNS-REQ#380
        CompassReporter.stopAndStartLevel(++level + ". Enable auto-discovery on evi-1");
        cmp1.configAndValidate(EvpnCommands.CONFIGURE_L2_SERVICES_EVPN_$_AUTO_DISCOVERY.args("evi-1"));

        // FLOW-010.S03 - covers EVPNS-REQ#30, EVPNS-REQ#40, EVPNS-REQ#50, EVPNS-REQ#380
        CompassReporter.stopAndStartLevel(++level + ". Set import-rt / export-rt on evi-1");
        cmp1.configAndValidate(EvpnCommands.CONFIGURE_L2_SERVICES_EVPN_$_IMPORT_RT_$.args("evi-1", "65000:1"));

        // FLOW-010.S04 - covers EVPNS-REQ#30, EVPNS-REQ#40, EVPNS-REQ#50, EVPNS-REQ#380
        CompassReporter.stopAndStartLevel(++level + ". Set export-rt on evi-1");
        cmp1.configAndValidate(EvpnCommands.CONFIGURE_L2_SERVICES_EVPN_$_EXPORT_RT_$.args("evi-1", "65000:1"));

        // FLOW-010.S05 - covers EVPNS-REQ#30, EVPNS-REQ#40, EVPNS-REQ#50, EVPNS-REQ#380
        CompassReporter.stopAndStartLevel(++level + ". Bind access circuit AC1 (agg-eth-1) to evi-1");
        cmp1.configAndValidate(EvpnCommands.CONFIGURE_L2_SERVICES_EVPN_$_INTERFACE_$.args("evi-1", "agg-eth-1"));

        // FLOW-010.S06 - covers EVPNS-REQ#30, EVPNS-REQ#40, EVPNS-REQ#50, EVPNS-REQ#380
        CompassReporter.stopAndStartLevel(++level + ". Bind access circuit AC2 (agg-eth-2) to evi-1");
        cmp1.configAndValidate(EvpnCommands.CONFIGURE_L2_SERVICES_EVPN_$_INTERFACE_$.args("evi-1", "agg-eth-2"));

        // FLOW-010.S07 - covers EVPNS-REQ#30, EVPNS-REQ#40, EVPNS-REQ#50, EVPNS-REQ#380
        CompassReporter.stopAndStartLevel(++level + ". Bind access circuit AC3 (agg-eth-3) to evi-1");
        cmp1.configAndValidate(EvpnCommands.CONFIGURE_L2_SERVICES_EVPN_$_INTERFACE_$.args("evi-1", "agg-eth-3"));

        // FLOW-010.S08 - covers EVPNS-REQ#30, EVPNS-REQ#40, EVPNS-REQ#50, EVPNS-REQ#380
        CompassReporter.stopAndStartLevel(++level + ". Verify evi-1 is up and all three ACs are bound");
        evpnUtils.verifyShowLines(EvpnCommands.SHOW_EVPN_GLOBAL_NAME_$.args("evi-1"), testParams.FLOW010_S08_EVPN_GLOBAL_LINES);
        CompassReporter.warning("FLOW-010.S08: Expected lines need real `show evpn global` output from the DUT - the CLI doc documents the syntax, not the layout.");

        // FLOW-010.S09 - covers EVPNS-REQ#30, EVPNS-REQ#40, EVPNS-REQ#50, EVPNS-REQ#380
        CompassReporter.stopAndStartLevel(++level + ". Verify the EVPN MAC address-table starts empty");
        evpnUtils.verifyShowLines(EvpnCommands.SHOW_EVPN_MAC_ADDRESS_TABLE_NAME_$.args("evi-1"), testParams.FLOW010_S09_MAC_TABLE_EMPTY_LINES);
        CompassReporter.warning("FLOW-010.S09: Needs real `show evpn mac-address-table` output.");

        // FLOW-010.S10 - covers RFC7432bis-section 7.3, RFC7432bis-section 11
        CompassReporter.stopAndStartLevel(++level + ". Verify the Type-3 IMET route for this EVI is originated into the local EVI table (no BGP peer on this rig)");
        evpnUtils.verifyShowLines(EvpnCommands.SHOW_BGP_L2VPN_EVPN_TABLE_EVI_NAME_$_DETAIL.args("evi-1"), testParams.FLOW010_S10_TYPE3_ADVERTISED_LINES);
        CompassReporter.warning("FLOW-010.S10: Needs real output of the route table above.");

        CompassReporter.stopLevel();
    }
}
